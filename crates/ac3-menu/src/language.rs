use crate::{Effect, Error, MenuContext, read_u32, require_bytes};

/// Displayed row to stored language ID, also the inverse permutation.
pub const LANGUAGE_SELECTION_TO_ID: [i32; 5] = [0, 2, 1, 4, 3];
pub const INPUT_PREVIOUS: u32 = 0x01;
pub const INPUT_NEXT: u32 = 0x02;
pub const INPUT_CONFIRM: u32 = 0x10;

/// Three words at the language-state pointer (`[0x800D8774]`).
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct LanguageState {
    /// 0: intro, 1: input, 2: exit.
    pub phase: i32,
    pub timer: i32,
    pub selection: i32,
}

impl LanguageState {
    pub const BYTE_LEN: usize = 12;
    pub fn from_bytes(bytes: &[u8]) -> Result<Self, Error> {
        require_bytes(bytes, Self::BYTE_LEN)?;
        Ok(Self {
            phase: read_u32(bytes, 0) as i32,
            timer: read_u32(bytes, 4) as i32,
            selection: read_u32(bytes, 8) as i32,
        })
    }
    pub fn write_into(&self, bytes: &mut [u8]) -> Result<(), Error> {
        require_bytes(bytes, Self::BYTE_LEN)?;
        for (index, value) in [self.phase, self.timer, self.selection]
            .into_iter()
            .enumerate()
        {
            bytes[index * 4..index * 4 + 4].copy_from_slice(&value.to_le_bytes());
        }
        Ok(())
    }
}

/// Layout generated by `0x800D0E78`; text, texture and color are host assets.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct LanguageRow {
    pub index: u8,
    /// Original visual slot is index + 1.
    pub visual_slot: u8,
    /// Original style value: 1 selected, 2 unselected.
    pub style: u8,
    pub visual_x: i32,
    pub x: i32,
    pub y: i32,
}

pub fn language_rows(selection: i32, timer: i32) -> [LanguageRow; 5] {
    std::array::from_fn(|index| {
        let index = index as i32;
        let d = timer.wrapping_sub(5).wrapping_add(index).max(0);
        let x = d.wrapping_mul(d.wrapping_neg());
        let selected = selection == index;
        LanguageRow {
            index: index as u8,
            visual_slot: (index + 1) as u8,
            style: if selected { 1 } else { 2 },
            visual_x: x,
            x: x.wrapping_add(80)
                .wrapping_add(if selected { 8 } else { 0 }),
            y: 120 + 59 * index,
        }
    })
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub struct LanguageUpdate {
    pub state: LanguageState,
    pub context: MenuContext,
    /// Result of the language callback to the nested menu dispatcher:
    /// initialization returns 1, ticking returns 0 or 0x100.
    pub callback_result: u32,
    pub effects: Vec<Effect>,
}

/// `0x800D13E4`: the switch default preserves unknown language IDs.
pub fn initialize_language(context: MenuContext) -> LanguageUpdate {
    let selection = map_language(context.language_id).unwrap_or(context.language_id);
    let mut effects = vec![Effect::SelectVisualPage { page: 2 }];
    effects.extend((1..=5).map(|slot| Effect::SetVisualOffset {
        slot,
        x: -625,
        y: 0,
    }));
    LanguageUpdate {
        state: LanguageState {
            phase: 0,
            timer: 25,
            selection,
        },
        context,
        callback_result: 1,
        effects,
    }
}

/// The pure state effects of `0x800D14E0` and its three phase callbacks.
///
/// Input bits must be the already processed game input at context `+0x12C`.
/// No raw controller mapping or key-repeat timing is implied. Effects preserve
/// call order, especially drawing before input modifies selection. Invalid
/// phases return an error instead of indexing beyond the original table.
pub fn tick_language(
    mut state: LanguageState,
    mut context: MenuContext,
    input_bits: u32,
) -> Result<LanguageUpdate, Error> {
    let mut effects = Vec::new();
    let phase_result = match state.phase {
        0 => {
            effects.push(Effect::DrawLanguageRows {
                rows: language_rows(state.selection, state.timer),
            });
            if state.timer > 0 {
                state.timer = state.timer.wrapping_sub(1);
                0
            } else {
                1
            }
        }
        1 => {
            effects.push(Effect::DrawLanguageRows {
                rows: language_rows(state.selection, 0),
            });
            if input_bits & INPUT_CONFIRM != 0 {
                if let Some(language) = map_language(state.selection) {
                    context.language_id = language;
                }
                effects.push(Effect::PlaySound { id: 0x3c });
                1
            } else {
                if input_bits & INPUT_NEXT != 0 {
                    state.selection = if state.selection < 4 {
                        state.selection.wrapping_add(1)
                    } else {
                        0
                    };
                    effects.push(Effect::PlaySound { id: 0x3d });
                } else if input_bits & INPUT_PREVIOUS != 0 {
                    state.selection = if state.selection > 0 {
                        state.selection.wrapping_sub(1)
                    } else {
                        4
                    };
                    effects.push(Effect::PlaySound { id: 0x3d });
                }
                0
            }
        }
        2 => {
            let shade = (state.timer.wrapping_mul(255) / 25) as u8;
            effects.push(Effect::DrawLanguageFade { shade });
            effects.push(Effect::DrawLanguageRows {
                rows: language_rows(state.selection, 0),
            });
            if state.timer < 25 {
                state.timer = state.timer.wrapping_add(1);
                0
            } else {
                effects.push(Effect::SelectVisualPage { page: 0 });
                2
            }
        }
        phase => return Err(Error::InvalidLanguagePhase(phase)),
    };
    let callback_result = if phase_result & 1 != 0 {
        state.phase = state.phase.wrapping_add(1);
        0
    } else if phase_result & 2 != 0 {
        context.progress_flags |= 1;
        0x100
    } else {
        0
    };
    Ok(LanguageUpdate {
        state,
        context,
        callback_result,
        effects,
    })
}

fn map_language(value: i32) -> Option<i32> {
    usize::try_from(value)
        .ok()
        .and_then(|index| LANGUAGE_SELECTION_TO_ID.get(index))
        .copied()
}
