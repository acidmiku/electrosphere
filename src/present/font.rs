/// Rows of each glyph from 0x20, bit 4 the leftmost column.
static GLYPHS: [[u8; GLYPH_HEIGHT]; 96] = build();

const fn build() -> [[u8; GLYPH_HEIGHT]; 96] {
    let mut glyphs = [[0u8; GLYPH_HEIGHT]; 96];
    let mut band = 0;
    while band < 12 {
        let mut row = 0;
        while row < GLYPH_HEIGHT {
            let line = ART[band * GLYPH_HEIGHT + row].as_bytes();
            let mut glyph = 0;
            while glyph < 8 {
                let mut column = 0;
                while column < GLYPH_WIDTH {
                    if line[glyph * ADVANCE + column] == b'#' {
                        glyphs[band * 8 + glyph][row] |= 0x10 >> column;
                    }
                    column += 1;
                }
                glyph += 1;
            }
            row += 1;
        }
        band += 1;
    }
    glyphs
}

/// The rows of `c` (bit 4 leftmost); characters outside printable ASCII
/// show as a box.
pub fn glyph(c: char) -> [u8; GLYPH_HEIGHT] {
    let code = u32::from(c);
    let index = if (0x20..0x7f).contains(&code) {
        code - 0x20
    } else {
        0x5f
    };
    GLYPHS[index as usize]
}

/// Width in pixels of `text` drawn with [`glyph`] (no trailing spacing).
pub fn text_width(text: &str) -> usize {
    (text.chars().count() * ADVANCE).saturating_sub(1)
}

/// Whether pixel (`x`, `y`) of `text`'s strip is set.
pub fn pixel(text: &str, x: usize, y: usize) -> bool {
    if y >= GLYPH_HEIGHT || x % ADVANCE >= GLYPH_WIDTH {
        return false;
    }
    text.chars()
        .nth(x / ADVANCE)
        .is_some_and(|c| glyph(c)[y] & (0x10 >> (x % ADVANCE)) != 0)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn glyphs_come_from_the_art() {
        assert_eq!(glyph(' '), [0; GLYPH_HEIGHT]);
        // 'A': .###. / #...# x3 / ##### / #...# x2
        assert_eq!(glyph('A'), [0x0e, 0x11, 0x11, 0x11, 0x1f, 0x11, 0x11, 0x00]);
        assert_eq!(glyph('g')[7], 0x0e, "descender row");
        assert_eq!(glyph('é'), glyph('\u{7f}'), "non-ASCII shows a box");
        // Every printable character but space has pixels.
        for c in '!'..='~' {
            assert!(glyph(c).iter().any(|&row| row != 0), "{c:?}");
        }
    }

    #[test]
    fn text_pixels_follow_the_advance() {
        assert_eq!(text_width(""), 0);
        assert_eq!(text_width("AB"), 11);
        // 'I' is .###. on its first row; 'B' starts at column 6.
        assert!(!pixel("IB", 0, 0));
        assert!(pixel("IB", 1, 0));
        assert!(!pixel("IB", 5, 0), "spacing column");
        assert!(pixel("IB", 6, 0));
        assert!(!pixel("IB", 1, GLYPH_HEIGHT));
    }
}
